class Converter:
    """
    Класс с методом преобразования вещественного числа по заданным правилам.
    """

    @staticmethod
    def do(x: float) -> int:
        """
        Возвращает целое число в зависимости от диапазона вещественного числа x.

        Правила:
        x >= 100.7 -> 1000
        0 < x < 100.7 -> int(x)
        x == 0.0 -> ValueError
        -30.4 <= x < 0 -> int(x) - 5
        x <= -30. -> -2000

        По условию вход всегда имеет один знак после запятой,
        поэтому между -30.5 и -30.4 нет допустимых значений.
        """

        if x >= 100.7:
            return 1000

        if x > 0:
            return int(x)

        if x == 0:
            raise ValueError("Значение 0.0 недопустимо")

        if x >= -30.4:
            return int(x) - 5

        # Для корректных входов с одним знаком после запятой
        # это означает диапазон (-inf; -30.5]
        return -2000